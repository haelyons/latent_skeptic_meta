    tot = {"groups": groups, "n_read": int(z["n_read"][0]),
           "gram": {}, "vec_sum": {}, "cross": {},
           "label_sum": {}, "label_sq": {}, "n_pos": {}}
    for i, g in enumerate(groups):
        tot["gram"][g] = z["gram__" + g]
