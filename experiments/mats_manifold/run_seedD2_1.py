#!/usr/bin/env python3
"""Measures a character-count curve and a periodic wobble at three probe widths.

WHAT THIS RUNS. One public checkpoint of one open language model reads fixed,
committed text. The text is prose hard-wrapped at nine line widths. At every token
position we know how many characters have passed since the last line break. A ridge
regression is a linear fit with a penalty on large weights. One such fit predicts that
count from the model's internal vector at that position. We report the fit quality on
held-out documents, one number per readout. At the best-scoring readout we then look
for a faint periodic pattern in the similarity structure of the per-count average
vectors. That pattern is the wobble. A label-shuffling comparison says whether the
wobble beats chance.

THE QUESTION. The wobble is measured at three probe widths: 140, 200 and 280
characters. If it beats chance at two or more widths, its period is compared across
them. A period fixed in characters is a property of the model. A period that grows in
step with the probe width is an artefact of the probe. If no width beats chance, that
is a negative, unless a separate check shows the wide probes could not have measured
anything at all.

THE COMPLETE SPECIFICATION is the design object inside
records/seedD2_1_design_diff_triage.json. This file implements it and changes nothing.
Every constant that design marks as a guess is binding here. So are the five committed
answers in records/GATE_COMMIT_seedD2_1.md.

WHAT DIFFERS FROM THE EARLIER RUNNER run_seedD2.py. That earlier run voided itself at
its own validity gate. Its proven arithmetic is reused here unchanged. Four things are
corrected, each named by the committed design:
  1. The readout is chosen, and the validity gate is read, from fit quality pooled over
     the SEVEN wrap widths 20 through 140 only. Training uses those seven widths only.
     Widths 200 and 280 are scored at every readout and never gated.
  2. The wobble is measured at that one chosen readout.
  3. The measurable-range check uses the PEARSON CORRELATION inside each label bin, and
     compares bins starting above label 175 against bins ending at or below label 140.
  4. The profile length is committed as the label count minus 20.

NO TEXT IS GENERATED ANYWHERE. The design says so in one line: "No text is generated by
the model; every measurement reads hidden activations from one deterministic forward
pass per document per wrap width." So this file has no sampling settings, no decoding,
and no answer parsing. The build brief that produced this file asks for a generation
stage, a reasoning-tag parser, and an answer extractor. Those three things cannot exist
for this experiment. That brief is a fixed template shared with a different,
text-generating project (pipeline.js line 104). The three closest real equivalents are
implemented and self-tested instead, and each is named where it is defined below. The
same choice was made, for the same reason, by this project's earlier runners
run_seedD.py and run_seedD2.py.

STAGES, in order, each runnable on its own:
  --stage extract    checks the text file and the download, then runs one forward pass
                     per text variant, and saves what the later stages need.
  --stage calibrate  fixes every remaining constant using training documents only, and
                     writes that record before any held-out number is computed.
  --stage generate   the same stage as calibrate. The build brief names this position
                     "generate"; nothing is generated, so the name is only an alias.
  --stage endpoints  computes the per-readout fit, the validity gate, the wobble at
                     each of the three probe widths, the shuffle comparisons, the
                     token-position control, and the measurable-range check.
  --stage all        extract, then calibrate, then endpoints.
  --selftest         standard library only. Loads no model, needs no graphics card, and
                     exits non-zero on any failure.

Only one model exists in this experiment, so only one is ever resident. It is loaded
once, in the first stage, in half precision, and released before any analysis stage.

Every result stage writes one self-describing record through provenance.py. A record
carries its own identity, its inputs with content hashes, its measurement, the rule
that judges it, and the resulting call. Every rule text here is written before any
value is known. Every per-width wobble record and every control record also carries the
validity gate's own decision, so no such record can be read without its void status.

A second run of this script on the same rented box is a rerun of one instrument. It is
not a replication. No output here calls it one.
"""

